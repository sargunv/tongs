private fun symbol960(name: String, pathData: String): ImageVector =
  ImageVector.Builder(
      name = name,
      defaultWidth = 24.dp,
      defaultHeight = 24.dp,
      viewportWidth = 960f,
      viewportHeight = 960f,
    )
    .addGroup(translationY = 960f)
    .addPath(addPathNodes(pathData), fill = SolidColor(Color.Black))
    .clearGroup()
    .build()
